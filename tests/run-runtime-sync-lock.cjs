'use strict';
const fs=require('fs');
const path=require('path');
const crypto=require('crypto');
const assert=require('assert');
const root=path.resolve(__dirname,'..');
const lock=JSON.parse(fs.readFileSync(path.join(root,'sync/runtime-sync-lock.v2.50.json'),'utf8'));
const sha=rel=>crypto.createHash('sha256').update(fs.readFileSync(path.join(root,rel))).digest('hex');
const H='8ee6bb98c22dc66ee72f49fa88b4f7fd05fce1c96a2932e28a1a8667c9d3932e';
const HH='487aa2620b5be99480a81d462082f1a35ee637ec2cc38ebf42b1bcf1103d06c9';
assert.strictEqual(lock.canonical_registry_hash,H);
assert.strictEqual(lock.hero_component_registry_hash,HH);
assert.strictEqual(lock.one_source_authority,'v1.7.2');
assert.strictEqual(lock.application_runtime_sync,'v2.50');
for(const [rel,key] of [['js/app.bundle.js','shared_gameplay_sha256'],['js/runtime-authority.js','runtime_authority_sha256'],['runtime-source/runtime/browser/runtime-authority.browser.js','runtime_source_browser_sha256'],['js/static-data.js','static_data_sha256'],['css/app.css','shared_ui_css_sha256'],['js/mobile-app-nav.js','mobile_app_nav_sha256']])assert.strictEqual(sha(rel),lock[key],rel);
assert.strictEqual(lock.local_ai,'v6.21');
assert.strictEqual(lock.tutorial,'v0.49');
assert.strictEqual(lock.pvp_reference,'v3.18');
assert.strictEqual(lock.audio_assets.coin_flip.sha256,sha('assets/audio/Coin Flip.mp3'));
assert.strictEqual(lock.audio_assets.card_sound.sha256,sha('assets/audio/Card Sound.mp3'));
