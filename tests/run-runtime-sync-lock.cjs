'use strict';
const fs=require('fs');
const path=require('path');
const crypto=require('crypto');
const assert=require('assert');
const root=path.resolve(__dirname,'..');
const lock=JSON.parse(fs.readFileSync(path.join(root,'sync/runtime-sync-lock.v2.35.json'),'utf8'));
const sha=rel=>crypto.createHash('sha256').update(fs.readFileSync(path.join(root,rel))).digest('hex');
const H='5812e107dbe82cef660975e091388eae1ad5a852c7be066c7443a5a321188bab';
assert.strictEqual(lock.canonical_registry_hash,H);
assert.strictEqual(lock.one_source_authority,'v1.4');
assert.strictEqual(lock.application_runtime_sync,'v2.35');
